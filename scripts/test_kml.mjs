import assert from 'node:assert/strict';
import fs from 'node:fs';
import {sceneToWgs84,measurementsKml,kmlToKmz} from '../dist/measurement-kml.mjs';
const origin=[716060,7854510,850];
const vertices=[{x:0,y:90,z:0},{x:500,y:150,z:0},{x:500,y:-20,z:900},{x:0,y:200,z:900}];
const points=vertices.map(p=>sceneToWgs84(p,origin,'EPSG:32723'));
assert.deepEqual(sceneToWgs84({...vertices[0],y:999},origin,'EPSG:32723'),points[0]);
assert.throws(()=>sceneToWgs84(vertices[0],origin,'EPSG:3857'));
assert.throws(()=>measurementsKml([]));
assert.throws(()=>measurementsKml([{type:'area',points:points.slice(0,2)}]));
assert.throws(()=>measurementsKml([{type:'distance',points:[{lat:NaN,lng:0},points[0]]}]));
const records=['2D','3D'].flatMap(source=>['distance','area'].map(type=>({type,source,month:'Setembro & <2026>',points:type==='area'?points:points.slice(0,2),attributes:{'Área & cota':'Teste <original>'}})));
const before=JSON.stringify(records),kml=measurementsKml(records);
assert.equal(JSON.stringify(records),before);
assert.ok(kml.includes('Setembro &amp; &lt;2026&gt;'));
assert.equal((kml.match(/<Placemark>/g)||[]).length,4);
fs.mkdirSync('tmp',{recursive:true});
fs.writeFileSync('tmp/measurements-test.kml',kml);
fs.writeFileSync('tmp/measurements-test.kmz',kmlToKmz(kml));
fs.writeFileSync('tmp/measurements-fixture.json',JSON.stringify({origin,vertices,points}));
console.log('KML: geometry validation, XML escaping, non-mutation and 3D flattening passed.');
